// Vice State — build entry point.
//
// Copies the studio (app/) and the preview screenshots into the output
// directory, then writes dossier.json through the vendored helper. The
// helper enforces the scorer's gate: how much text, how many screenshots
// at what size, and how many bytes app/ may weigh.
//
// Outside the grader container set MAKEFUN_OUTPUT_DIR (the default /output
// is usually not writable). Serve the app with `node serve.ts --port 8080`.

import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-app.ts';

const here = fileURLToPath(new URL('.', import.meta.url));
const out = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(out, { recursive: true });
cpSync(join(here, 'app'), join(out, 'app'), { recursive: true });
mkdirSync(join(out, 'screenshots'), { recursive: true });
if (existsSync(join(here, 'screenshots'))) {
  cpSync(join(here, 'screenshots'), join(out, 'screenshots'), { recursive: true });
}

// Gate constants mirror the scorer's reference/gate.json.
writeFileSync(
  join(out, 'dossier.json'),
  buildDossier(out, {
    text_max_bytes: 163840,
    screenshots: { max: 4, max_bytes: 262144 },
    app_max_files: 993,
    app_max_bytes: 50331648,
    app_path_max_bytes: 1000,
  }),
);
